-- 3) DataPump Job History Table
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'DATAPUMP_JOB_HISTORY';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE datapump_job_history (
        job_id          VARCHAR2(50 CHAR) NOT NULL,
        operation       VARCHAR2(20 CHAR) NOT NULL,
        database_name   VARCHAR2(128 CHAR) NOT NULL,
        status          VARCHAR2(20 CHAR) DEFAULT 'running' NOT NULL,
        started_at      TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        completed_at    TIMESTAMP(6) WITH TIME ZONE,
        dump_file       VARCHAR2(500 CHAR),
        transfer_status VARCHAR2(500 CHAR),
        message         CLOB,
        requested_by    VARCHAR2(128 CHAR),
        params_json     CLOB,
        CONSTRAINT pk_datapump_job_history PRIMARY KEY (job_id)
      )
    ]';
  END IF;
END;
/

-- Indexes for fast lookup
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_indexes WHERE index_name = 'IX_DATAPUMP_JOB_STARTED';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX ix_datapump_job_started ON datapump_job_history (started_at DESC)';
  END IF;
  
  SELECT COUNT(*) INTO v_count FROM user_indexes WHERE index_name = 'IX_DATAPUMP_JOB_DB_STATUS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX ix_datapump_job_db_status ON datapump_job_history (database_name, status, started_at DESC)';
  END IF;
END;
