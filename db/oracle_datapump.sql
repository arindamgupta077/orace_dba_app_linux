-- 1) DataPump Export Templates Table
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'DATAPUMP_EXPDP_TEMPLATES';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE datapump_expdp_templates (
        template_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
        template_name      VARCHAR2(128 CHAR) NOT NULL,
        database_name      VARCHAR2(128 CHAR),
        created_by         VARCHAR2(128 CHAR) NOT NULL,
        created_at         TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
        params_json        CLOB,
        dump_transfer_req  VARCHAR2(10 CHAR) DEFAULT 'no',
        transfer_server    VARCHAR2(128 CHAR),
        compression        VARCHAR2(50 CHAR),
        schemas_list       VARCHAR2(4000 CHAR),
        CONSTRAINT pk_datapump_expdp_templates PRIMARY KEY (template_id)
      )
    ]';
  END IF;
END;
/

